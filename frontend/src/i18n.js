const I18nContext = createContext({ lang: "it", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem("21r_lang") || "it");
  useEffect(() => { localStorage.setItem("21r_lang", lang); }, [lang]);
  const setLang = (l) => setLangState(l);
  const t = useMemo(() => (key) => (dict[lang] && dict[lang][key]) || key, [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }

